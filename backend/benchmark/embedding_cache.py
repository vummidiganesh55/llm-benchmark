import hashlib
import json
from pathlib import Path
from typing import Any


class EmbeddingCache:
    """
    Cache embedding vectors to avoid repeated embedding requests.

    The cache key is generated from:
        model + input text

    This prevents embeddings generated by different models from
    being incorrectly reused.
    """

    def __init__(
        self,
        cache_path: str = "results/embedding_cache.json",
    ):
        self.cache_path = Path(cache_path)

        self._cache: dict[str, list[float]] = {}

        self.hits = 0
        self.misses = 0

        self._load()

    # =========================================================
    # CACHE KEY
    # =========================================================

    @staticmethod
    def _create_key(
        model: str,
        text: str,
    ) -> str:
        """
        Create a deterministic SHA-256 cache key.
        """

        normalized_text = str(text).strip()

        raw_key = (
            f"{model}::{normalized_text}"
        )

        return hashlib.sha256(
            raw_key.encode("utf-8")
        ).hexdigest()

    # =========================================================
    # LOAD
    # =========================================================

    def _load(self) -> None:
        """
        Load existing cache from disk.
        """

        if not self.cache_path.exists():
            return

        try:
            with open(
                self.cache_path,
                "r",
                encoding="utf-8",
            ) as file:

                data = json.load(file)

            if not isinstance(data, dict):
                return

            cache = data.get(
                "embeddings",
                {},
            )

            if not isinstance(cache, dict):
                return

            self._cache = cache

        except (
            OSError,
            json.JSONDecodeError,
        ):
            # Corrupted/unreadable cache should never
            # prevent the benchmark from running.
            self._cache = {}

    # =========================================================
    # SAVE
    # =========================================================

    def _save(self) -> None:
        """
        Persist cache to disk.
        """

        self.cache_path.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        payload = {
            "embeddings": self._cache,
        }

        temporary_path = self.cache_path.with_suffix(
            ".tmp"
        )

        with open(
            temporary_path,
            "w",
            encoding="utf-8",
        ) as file:

            json.dump(
                payload,
                file,
                ensure_ascii=False,
            )

        temporary_path.replace(
            self.cache_path
        )

    # =========================================================
    # GET
    # =========================================================

    def get(
        self,
        model: str,
        text: str,
    ) -> list[float] | None:
        """
        Return a cached embedding.

        Returns None when the embedding is not cached.
        """

        key = self._create_key(
            model=model,
            text=text,
        )

        embedding = self._cache.get(
            key
        )

        if embedding is None:

            self.misses += 1

            return None

        self.hits += 1

        return embedding

    # =========================================================
    # SET
    # =========================================================

    def set(
        self,
        model: str,
        text: str,
        embedding: list[float],
    ) -> None:
        """
        Store an embedding in the cache.
        """

        key = self._create_key(
            model=model,
            text=text,
        )

        self._cache[key] = embedding

        self._save()

    # =========================================================
    # GET OR COMPUTE
    # =========================================================

    def get_or_compute(
        self,
        model: str,
        text: str,
        compute_function,
    ) -> list[float]:
        """
        Return cached embedding or compute and cache it.
        """

        cached_embedding = self.get(
            model=model,
            text=text,
        )

        if cached_embedding is not None:
            return cached_embedding

        embedding = compute_function()

        if embedding is None:
            raise ValueError(
                "Embedding function returned None."
            )

        if not isinstance(
            embedding,
            list,
        ):
            embedding = list(embedding)

        self.set(
            model=model,
            text=text,
            embedding=embedding,
        )

        return embedding

    # =========================================================
    # CACHE STATISTICS
    # =========================================================

    def get_stats(self) -> dict[str, Any]:
        """
        Return cache statistics.
        """

        total_requests = (
            self.hits + self.misses
        )

        hit_rate = (
            self.hits / total_requests
            if total_requests > 0
            else 0.0
        )

        return {
            "entries": len(self._cache),
            "hits": self.hits,
            "misses": self.misses,
            "total_requests": total_requests,
            "hit_rate": round(
                hit_rate,
                4,
            ),
        }

    # =========================================================
    # CLEAR
    # =========================================================

    def clear(self) -> None:
        """
        Clear all cached embeddings.
        """

        self._cache = {}

        self.hits = 0
        self.misses = 0

        if self.cache_path.exists():
            self.cache_path.unlink()